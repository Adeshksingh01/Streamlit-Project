# Commented out IPython magic to ensure Python compatibility.
# %pip install streamlit

import streamlit as st

st.title("Student Information Portal")
st.write("Please fill out the form below to enter and view student details.")

st.divider()

# Input Fields
name = st.text_input("Student Name", placeholder="e.g., Jane Doe")

roll_number = st.number_input("Roll Number", min_value=1, step=1)

courses = ["B.Tech", "B.Sc", "B.Com", "B.A", "M.Tech", "MBA"]
course = st.selectbox("Select Course", courses)


available_subjects = [
    "Mathematics", "Physics", "Chemistry",
    "Computer Science", "Biology", "Economics",
    "Accounts", "English"
]
subjects = st.multiselect("Select Subjects", available_subjects)


marks = st.slider("Marks Obtained", min_value=0, max_value=100, value=50)

st.divider()


if st.button("Submit Details"):

    if not name.strip():
        st.error("Please enter the student's name before submitting.")
    elif not subjects:
        st.warning("Please select at least one subject.")
    else:

        st.success("Student details submitted successfully!")


        st.subheader("Submitted Information")


        st.markdown(f"**Name:** {name}")
        st.markdown(f"**Roll Number:** {roll_number}")
        st.markdown(f"**Course:** {course}")


        subjects_formatted = ", ".join(subjects)
        st.markdown(f"**Subjects:** {subjects_formatted}")

        st.markdown(f"**Marks:** {marks}/100")